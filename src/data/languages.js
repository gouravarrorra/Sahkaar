// Fallback to English for missing translations
export function getString(lang, key) {
  return strings[lang]?.[key] || strings.en[key] || key;
}

export function getGreeting(lang) {
  const hour = new Date().getHours();
  if (hour < 12) return getString(lang, 'goodMorning');
  if (hour < 17) return getString(lang, 'goodAfternoon');
  return getString(lang, 'goodEvening');
}

